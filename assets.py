"""Builds Stone Skin's item records: the Stoneskin Elixir.

The elixir clones Brush Scrub 01 (device 1/9, so the game's own double-click use
mode applies and the game adds no effect of its own) with Elixir P1's bottle
model and size, and joins two civilian loot tables. Drinking it is the addon's
item.use handler (scripts/main.lua).

    python -B assets.py --inputs <folder with objdb.rdb, objstrings.rdb> --out <new folder>

Writes <out>/objdb.rdb, <out>/objstrings.rdb (whole files, for records_delta.py)
and <out>/elixir.lua (the built record id). The ExaniMate format library is found
through EXANIMATE_TOOLS (its tools/exanimate folder); tools/make_dist.py sets it."""
import argparse
import os
import sys
from pathlib import Path

if os.environ.get('EXANIMATE_TOOLS'):
    sys.path.insert(0, os.environ['EXANIMATE_TOOLS'])
from exanimate import rdb  # noqa: E402

ELIXIR_NAME = 'Stoneskin Elixir'
ELIXIR_MODEL = 'Bottle_Med A1'  # Elixir P1's bottle; must match ELIXIR_MODEL in scripts/config.lua
ELIXIR_TEXT = ('A gritty, ochre draught. Double-click it, then click anything to drink: for a minute '
               'your skin sets into thick stone plates. Blades skate off; hammers shatter it.')
LOOT_TABLES = ('+Drop Tables/Civ LC Personal', '+Drop Tables/Civ MC Personal')


def build(inputs: Path, output: Path) -> int:
    if output.exists():
        raise ValueError('output must be a new folder')
    data = (inputs / 'objdb.rdb').read_bytes()
    strings_data = (inputs / 'objstrings.rdb').read_bytes()
    db, strings = rdb.parse(data), rdb.strings_package(strings_data)
    if any(r.name == ELIXIR_NAME for r in db.records):
        raise ValueError('input database already has a Stoneskin Elixir; build from inputs without this mod')
    brush = next(r for r in db.records if r.name == 'Brush Scrub 01')
    bottle = next(r for r in db.records if r.name == 'Elixir P1')
    elixir = rdb.clone_record(db, brush.id, ELIXIR_NAME, ELIXIR_MODEL)
    rdb.set_item_size(elixir, rdb.item_size(bottle) or 2)
    strings += [(0, 1, ELIXIR_NAME), (0, 1, ELIXIR_TEXT)]
    rdb.set_display_strings(elixir, len(strings) - 1, len(strings))
    for table in (r for r in db.records if db.path(r) in LOOT_TABLES):
        rdb.add_drop_entry(db, table.id, elixir.id, a=6)
    output.mkdir(parents=True)
    (output / 'objdb.rdb').write_bytes(rdb.pack(db))
    (output / 'objstrings.rdb').write_bytes(rdb.pack_strings(strings, strings_data))
    (output / 'elixir.lua').write_text(
        '-- Generated by assets.py; do not edit by hand.\n'
        f'return {{elixir_item_id = {elixir.id:#x}}}\n')
    print(f'stoneskin elixir id {elixir.id:#x}')
    return elixir.id


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--inputs', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    build(args.inputs.resolve(), args.out.resolve())
